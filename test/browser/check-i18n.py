"""Run after npm run build, with i18n-server.mjs listening on port 43911.
Requires Python Playwright and Chromium. Uses only simulated MCP tools.
"""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

BASE = 'http://127.0.0.1:43911'
OUTPUT = Path(__file__).resolve().parents[2] / 'output' / 'playwright'
OUTPUT.mkdir(parents=True, exist_ok=True)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    context = browser.new_context(locale='en-US', viewport={'width':1100,'height':900})
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(BASE+'/?locale=ja-JP')
    page.wait_for_load_state('networkidle')
    frame = page.frame_locator('#app')
    expect(frame.locator('h1')).to_have_text('3D モデルを作成')
    expect(frame.locator('html')).to_have_attribute('lang','ja')
    frame.locator('[data-mode="text"]').click()
    frame.locator('#prompt').fill('用户输入 日本語 $& <tag>')
    frame.locator('#characterName').fill('用户角色 日本語')
    frame.locator('#faces').fill('30000')
    headings = {'en':'Create 3D model','zh-CN':'创建 3D 模型','zh-TW':'創建 3D 模型','ja':'3D モデルを作成'}
    for locale,heading in headings.items():
        frame.locator('#language').select_option(locale)
        expect(frame.locator('html')).to_have_attribute('lang',locale)
        expect(frame.locator('h1')).to_have_text(heading)
        expect(frame.locator('#prompt')).to_have_value('用户输入 日本語 $& <tag>')
        expect(frame.locator('#characterName')).to_have_value('用户角色 日本語')
        expect(frame.locator('#faces')).to_have_value('30000')
        if locale=='ja': page.screenshot(path=str(OUTPUT/'workbench-ja.png'),full_page=True)
    page.reload()
    page.wait_for_load_state('networkidle')
    expect(frame.locator('#language')).to_have_value('ja')
    page.evaluate("window.setHostLocale('zh-CN')")
    expect(frame.locator('html')).to_have_attribute('lang','ja')
    frame.locator('#language').select_option('system')
    expect(frame.locator('html')).to_have_attribute('lang','zh-CN')
    page.evaluate("window.setHostLocale('zh-Hant')")
    expect(frame.locator('html')).to_have_attribute('lang','zh-TW')
    # Two iframe apps share manual preferences via the browser storage event.
    sibling=context.new_page()
    sibling.goto(BASE+'/?locale=en-US')
    sibling.wait_for_load_state('networkidle')
    sibling_frame=sibling.frame_locator('#app')
    frame.locator('#language').select_option('en')
    expect(sibling_frame.locator('#language')).to_have_value('en')
    expect(sibling_frame.locator('h1')).to_have_text('Create 3D model')
    frame.locator('[data-view="assets"]').click()
    expect(frame.locator('h1')).to_have_text('3D assets')
    expect(frame.locator('.asset-name')).to_have_text('用户模型 日本語')
    frame.locator('#language').select_option('ja')
    expect(frame.locator('.asset-name')).to_have_text('用户模型 日本語')
    frame.locator('[data-view="tasks"]').click()
    expect(frame.locator('h1')).to_have_text('タスク')
    expect(frame.locator('#taskGroupFilter')).to_have_count(0)
    frame.locator('#language').select_option('system')
    page.request.get(BASE+'/unknown-quote')
    frame.locator('.task-row').click()
    frame.locator('[data-action="submitDraft"]').click()
    expect(frame.locator('#confirmDialog')).to_be_visible()
    expect(frame.locator('#confirmSubmit')).to_be_disabled()
    frame.locator('#unknownCost').check()
    page.evaluate("window.setHostLocale('en-US')")
    expect(frame.locator('#confirmTitle')).to_have_text('Confirm Model generation')
    expect(frame.locator('#unknownCost')).to_be_checked()
    expect(frame.locator('#confirmSubmit')).to_be_enabled()
    frame.locator('#confirmCancel').click()
    frame.locator('[data-action="submitDraft"]').click()
    expect(frame.locator('#unknownCost')).not_to_be_checked()
    expect(frame.locator('#confirmSubmit')).to_be_disabled()
    frame.locator('#confirmCancel').click()
    frame.locator('[data-view="assets"]').click()
    frame.locator('[data-action="selectAsset"]').click()
    frame.locator('[data-action="assetDetail"]').click()
    frame.locator('[data-action="export"]').click()
    frame.locator('#exportFormat').select_option('fbx')
    frame.locator('#exportSize').select_option('2048')
    frame.locator('#exportAnimation').check()
    page.evaluate("window.setHostLocale('ja-JP')")
    expect(frame.locator('#confirmTitle')).to_have_text('3D モデルをエクスポート')
    expect(frame.locator('#exportFormat')).to_have_value('fbx')
    expect(frame.locator('#exportSize')).to_have_value('2048')
    expect(frame.locator('#exportAnimation')).to_be_checked()
    frame.locator('#confirmCancel').click()
    stats=page.request.get(BASE+'/stats').json()
    assert not any(call['name'] in ['tripo_submit_task','tripo_generate_model'] for call in stats['calls'])
    print('PASS workbench: auto locale, 4 languages, preserved input, storage, host changes, unchanged asset names, no submissions')
    sibling.close()
    page.request.get(BASE+'/reset')
    page.goto(BASE+'/?locale=ja-JP&card=review')
    page.wait_for_load_state('networkidle')
    frame=page.frame_locator('#app')
    expect(frame.locator('.configuration h2')).to_have_text('高精細モデル生成')
    expect(frame.locator('.source-picture img')).to_have_count(4)
    first_image=frame.locator('.source-picture img').first
    first_image.evaluate('node => window.sourceImageBeforeSwitch = node')
    deadline=page.request.get(BASE+'/stats').json()['review']['deadline_at']
    frame.locator('#language').select_option('en')
    expect(frame.locator('.configuration h2')).to_have_text('High Detail model generation')
    expect(frame.locator('.source-caption').first).to_have_text('Front')
    expect(frame.locator('.source-replace').first).to_have_attribute('aria-label','Replace Front image')
    assert first_image.evaluate('node => node === window.sourceImageBeforeSwitch')
    after=page.request.get(BASE+'/stats').json()
    assert after['review']['deadline_at']==deadline
    assert after['review']['status']=='pending'
    assert not any(call.get('arguments',{}).get('action') in ['edit','save','confirm','cancel'] for call in after['calls'])
    # Editing pauses the existing review; changing language neither saves nor recreates it.
    frame.locator('[data-field="face_limit"]').fill('25000')
    expect(frame.locator('.config-notice')).to_have_text('Settings changed')
    frame.locator('#language').select_option('zh-TW')
    expect(frame.locator('[data-field="face_limit"]')).to_have_value('25000')
    expect(frame.locator('.config-notice')).to_contain_text('配置已修改')
    expect(frame.locator('.configuration h2')).to_have_text('高精度模型生成')
    frame.locator('#language').select_option('ja')
    expect(frame.locator('.config-actions button[type="submit"]')).to_have_text('保存して見積もりを更新')
    expect(frame.locator('[data-field="face_limit"]')).to_have_value('25000')
    page.screenshot(path=str(OUTPUT/'configuration-ja.png'),full_page=True)
    frame.locator('.config-actions button[type="submit"]').click()
    expect(frame.locator('form')).to_have_attribute('aria-busy','true')
    frame.locator('#language').select_option('en')
    expect(frame.locator('.config-actions button[type="submit"]')).to_have_text('Saving & updating estimate…')
    expect(frame.locator('.config-actions button[type="submit"]')).to_be_disabled()
    expect(frame.locator('.config-notice')).to_contain_text('Auto-submit in')
    stats=page.request.get(BASE+'/stats').json()
    saves=[call for call in stats['calls'] if call.get('arguments',{}).get('action')=='save']
    assert len(saves)==1 and saves[0]['arguments']['input']['face_limit']==25000
    assert not any(call.get('arguments',{}).get('action')=='confirm' for call in stats['calls'])
    print('PASS configuration: live labels/accessibility, preserved images/edits, unchanged deadline, pending save, one save and no dispatch')
    for kind,heading in [('quote','モデル生成 · クレジット見積もり'),('catalog',None)]:
        page.goto(BASE+f'/?locale=ja-JP&card={kind}')
        page.wait_for_load_state('networkidle')
        frame=page.frame_locator('#app')
        frame.locator('#language').select_option('ja')
        if heading:
            expect(frame.locator('.quote-card h2')).to_have_text(heading)
            expect(frame.locator('.quote-cost strong')).to_have_text('40')
            expect(frame.locator('.quote-card')).to_contain_text('25 クレジット')
            page.screenshot(path=str(OUTPUT/'quote-ja.png'),full_page=True)
        else:
            expect(frame.locator('.operation-catalog li')).to_have_count(28)
            expect(frame.locator('.operation-catalog')).to_contain_text('ローカル編集')
        frame.locator('#language').select_option('en')
        expect(frame.locator('#status')).to_have_text('Estimated cost' if heading else 'Available features')
    page.set_viewport_size({'width':390,'height':844})
    page.goto(BASE+'/?locale=ja-JP')
    page.wait_for_load_state('networkidle')
    frame=page.frame_locator('#app')
    frame.locator('#language').select_option('ja')
    assert frame.locator('html').evaluate('node=>node.scrollWidth <= window.innerWidth'), 'narrow viewport overflow'
    page.screenshot(path=str(OUTPUT/'workbench-ja-narrow.png'),full_page=True)
    page.request.get(BASE+'/reset')
    page.goto(BASE+'/?locale=ja-JP&card=review')
    page.wait_for_load_state('networkidle')
    frame=page.frame_locator('#app')
    for locale in ['en','ja']:
        frame.locator('#language').select_option(locale)
        assert frame.locator('html').evaluate('node=>node.scrollWidth <= window.innerWidth'), f'{locale} narrow card overflow'
    page.screenshot(path=str(OUTPUT/'configuration-ja-narrow.png'),full_page=True)
    assert not errors, errors
    print('PASS quotes/catalog/narrow layout: localized costs and all 28 operations; no browser errors')
    context.close()
    # Storage restrictions in sandboxed hosts must not prevent rendering or switching.
    restricted=browser.new_context(locale='en-US')
    restricted.add_init_script("Storage.prototype.getItem=()=>{throw Error('blocked')};Storage.prototype.setItem=()=>{throw Error('blocked')}")
    restricted_page=restricted.new_page()
    restricted_page.on('pageerror',lambda error: errors.append(str(error)))
    restricted_page.goto(BASE+'/?locale=fr-FR')
    restricted_page.wait_for_load_state('networkidle')
    restricted_frame=restricted_page.frame_locator('#app')
    expect(restricted_frame.locator('h1')).to_have_text('Create 3D model')
    restricted_frame.locator('#language').select_option('ja')
    expect(restricted_frame.locator('h1')).to_have_text('3D モデルを作成')
    restricted_page.reload()
    restricted_page.wait_for_load_state('networkidle')
    expect(restricted_frame.locator('h1')).to_have_text('Create 3D model')
    assert not errors,errors
    restricted.close()
    print('PASS restricted storage: browser fallback and manual switching remain available')
    browser.close()
